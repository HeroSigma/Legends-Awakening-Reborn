"""Generate exact EV prefix counts; replaces expensive ARM 64-bit division."""
from pathlib import Path
from math import comb

def choose(n,k):
    return comb(n,k) if n>=k>=0 else 0

def render():
    rows=[]
    for n in range(6):
        values=[sum((-1)**k*comb(n,k)*choose(b-256*k+n+1,n+1) for k in range(n+1)) for b in range(511)]
        rows.append(" {\n"+"\n".join("  "+", ".join("UINT64_C(%d)"%v for v in values[i:i+6])+"," for i in range(0,511,6))+"\n }")
    return "/* Generated by generate_ev_prefix.py; exact bounded EV counts. */\nstatic const uint64_t sEvPrefix[6][511] = {\n"+",\n".join(rows)+"\n};\n"
if __name__=='__main__':
    Path(__file__).with_name('compact_pc_ev_prefix.inc').write_text(render())
