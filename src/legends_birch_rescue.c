static const struct SpriteTemplate sRescueLightningTemplate = {
    .tileTag = TAG_RESCUE_LIGHTNING, .paletteTag = TAG_RESCUE_LIGHTNING,
    .oam = &sRescueLightningOam, .anims = gDummySpriteAnimTable,
    .images = NULL, .affineAnims = gDummySpriteAffineAnimTable,
    .callback = SpriteCallbackDummy,
};
static void Task_RescueLightning(u8 taskId)
{
    struct Task *task = &gTasks[taskId];
    if (++task->data[0] < 42)
    {
        if (task->data[1] != MAX_SPRITES)
            gSprites[task->data[1]].invisible = (task->data[0] % 6) >= 4;
        BlendPalettes(PALETTES_ALL, (task->data[0] % 12 < 6) ? 8 : 0, RGB_WHITE);
        SetCameraPanning((task->data[0] & 1) ? 2 : -2, 0);
        return;
    }
    if (task->data[1] != MAX_SPRITES)
        DestroySprite(&gSprites[task->data[1]]);
    FreeSpriteTilesByTag(TAG_RESCUE_LIGHTNING);
    FreeSpritePaletteByTag(TAG_RESCUE_LIGHTNING);
    BlendPalettes(PALETTES_ALL, 0, RGB_WHITE);
    SetCameraPanning(0, 0);
    InstallCameraPanAheadCallback();
    DestroyTask(taskId);
    ScriptContext_Enable();
}
void LegendsBirchRescueThunderbolt(void)
{
    const struct SpriteSheet sheet = {sRescueLightningTiles, sizeof(sRescueLightningTiles), TAG_RESCUE_LIGHTNING};
    const struct SpritePalette palette = {sRescueLightningPalette, TAG_RESCUE_LIGHTNING};
    u8 objectId, spriteId = MAX_SPRITES;
    u8 taskId = CreateTask(Task_RescueLightning, 80);
    LoadSpriteSheet(&sheet);
    LoadSpritePalette(&palette);
    if (!TryGetObjectEventIdByLocalIdAndMap(LOCALID_ROUTE101_ZIGZAGOON, gSaveBlock1Ptr->location.mapNum, gSaveBlock1Ptr->location.mapGroup, &objectId))
    {
        struct Sprite *target = &gSprites[gObjectEvents[objectId].spriteId];
        spriteId = CreateSprite(&sRescueLightningTemplate, target->x + target->x2, target->y + target->y2 - 12, 0);
        if (spriteId != MAX_SPRITES)
            gSprites[spriteId].coordOffsetEnabled = target->coordOffsetEnabled;
    }
    gTasks[taskId].data[1] = spriteId;
    SetCameraPanningCallback(NULL);
    PlaySE(SE_M_THUNDERBOLT);
}
