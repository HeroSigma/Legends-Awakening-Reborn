bool32 LaPcRetiredMap(u32 group, u32 num)
{
    u32 i;
    for(i=0;i<ARRAY_COUNT(sRetiredMaps);i++)
        if(MAP_GROUP(sRetiredMaps[i])==group && MAP_NUM(sRetiredMaps[i])==num) return TRUE;
    return FALSE;
}
